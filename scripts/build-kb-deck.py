def find_page_slots():
    """쪽번호가 들어 있는 문단의 위치를 원문에서 찾아 둔다.

    위치를 '대개 4번째'로 어림잡았더니, 쪽번호가 아예 없는 장(25쪽 '우리가
    가려는 곳')의 본문을 숫자로 덮어써 「지금」 상자에 '28'이 박혔다.
    원문에 적힌 쪽번호(그 장의 순서-1)와 정확히 같은 문자열만 골라 잡는다.
    """
    slots = {}
    for n, texts in DECK.items():
        # '①' 도 isdigit() 이 참이라 아스키 숫자만 센다.
        cand = [i for i, t in enumerate(texts)
                if isinstance(t, str) and t.isascii() and t.isdigit()]
        if len(cand) == 1:
            slots[n] = cand[0]          # 숫자가 하나뿐이면 그게 쪽번호다
        elif str(n - 1) in texts:
            slots[n] = texts.index(str(n - 1))
    return slots


PAGE_IDX = find_page_slots()


def apply_page_numbers():
    """쪽번호를 ORDER 에서 다시 계산해 넣는다.

    손으로 적어두면 순서를 바꿀 때마다 전부 어긋난다(실측: 19번을 앞으로 옮기니
    11장이 틀어졌다).
    """
    for pos, n in enumerate(ORDER, start=1):
        idx = PAGE_IDX.get(n)
        if idx is not None:
            DECK[n][idx] = str(pos - 1)


def replace_slide(xml: str, texts):
    """첫 런에 새 문장을 넣고, 같은 문단의 나머지 런은 반드시 비운다.

    처음엔 첫 런만 바꿨다. 문단마다 런이 하나인 줄 알았는데 슬라이드마다
    달랐고, 남은 런의 옛 글자가 새 문장 뒤에 그대로 붙었다
    (실측: "…차별점해법 효과 차별점", "금융소득증명서악순환입니다").
    뒤에서부터 지워야 앞 런의 위치가 밀리지 않는다.
    """
    paras = list(re.finditer(r"<a:p>.*?</a:p>", xml, re.S))
    out, last, idx = [], 0, 0
    for m in paras:
        seg = m.group(0)
        runs = list(re.finditer(r"(<a:t>)(.*?)(</a:t>)", seg, re.S))
        if runs:
            new = texts[idx] if idx < len(texts) else ""
            idx += 1
            if new is not None:
                for r in reversed(runs[1:]):
                    seg = seg[: r.start(2)] + seg[r.end(2) :]
                r0 = runs[0]
                seg = seg[: r0.start(2)] + esc(new) + seg[r0.end(2) :]
        out.append(xml[last : m.start()] + seg)
        last = m.end()
    out.append(xml[last:])
    return "".join(out)


def esc(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace("\n", "\u2028"))  # 줄바꿈은 도형 안 줄바꿈 문자로


def reorder(xml: str) -> str:
    """presentation.xml 의 슬라이드 목록을 ORDER 대로 다시 늘어놓는다.

    슬라이드 파일 자체는 건드리지 않는다 — 목록의 순서만 바꾸면 된다.
    파일 이름(slide19.xml)과 보이는 순서는 원래 별개다.
    """
    m = re.search(r"(<p:sldIdLst>)(.*?)(</p:sldIdLst>)", xml, re.S)
    if not m:
        raise SystemExit("슬라이드 목록을 찾지 못했습니다")
    ids = re.findall(r"<p:sldId[^>]*/>", m.group(2))
    # 27번 이상은 아직 없다 — add-slides.py 가 나중에 끼워 넣는다.
    here = [n for n in ORDER if n <= len(ids)]
    if len(ids) != 26:
        raise SystemExit(f"원본 장 수가 26이 아닙니다: {len(ids)}")
    # 목록은 원래 1,2,3… 순이므로 n번째 항목이 곧 slide{n}.xml 이다.
    return xml[: m.start(2)] + "".join(ids[n - 1] for n in here) + xml[m.end(2) :]


def main():
    if not os.path.exists(SRC):
        raise SystemExit(f"원본을 찾을 수 없습니다: {SRC}")
    apply_page_numbers()
    # PowerPoint 로 열어둔 채로 다시 만들면 잠겨서 덮어쓸 수 없다.
    # 작업이 멈추지 않도록 옆 이름으로 저장하고, 끝에 어디에 저장됐는지 알린다.
    dst = DST
    if os.path.exists(dst):
        try:
            os.remove(dst)
        except PermissionError:
            base, ext = os.path.splitext(DST)
            n = 2
            while os.path.exists(f"{base}_v{n}{ext}"):
                n += 1
            dst = f"{base}_v{n}{ext}"
            print(f"※ 원본이 열려 있어 새 파일로 저장합니다: {os.path.basename(dst)}")
    zin = zipfile.ZipFile(SRC)
    zout = zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED)
    changed = 0
    for item in zin.infolist():
        data = zin.read(item.filename)
        m = re.match(r"ppt/slides/slide(\d+)\.xml$", item.filename)
        if m:
            n = int(m.group(1))
            if n in DECK:
                xml = data.decode("utf-8")
                xml = replace_slide(xml, DECK[n])
                data = xml.encode("utf-8")
                changed += 1
        elif item.filename == "ppt/presentation.xml":
            data = reorder(data.decode("utf-8")).encode("utf-8")
        zout.writestr(item, data)
    zout.close()
    moved = [n for i, n in enumerate(ORDER, start=1) if i != n]
    print(f"슬라이드 {changed}장 교체 · 순서 조정 {len(moved)}장 → {dst}")


if __name__ == "__main__":
    main()
